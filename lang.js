let activeLanguage;
function setLang(lang) {
    activeLanguage = lang === 'ru' ? 'ru' : 'en';
    try { localStorage.setItem('lang', activeLanguage); } catch { /* Keep language switching available for guests. */ }
    applyLang(lang);
    updateLangButtons(lang);
    document.dispatchEvent(new Event('languagechange'));
}

function applyLang(lang) {
    const t = translations[lang] || translations.en;
    document.documentElement.lang = translations[lang] ? lang : 'en';
    
    document.querySelectorAll('[data-translate]').forEach(el => {
        const key = el.getAttribute('data-translate');
        if (t[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = t[key];
            } else {
                el.textContent = t[key];
            }
        }
    });

    const userNameEl = document.querySelector('.user-name');
    let isLoggedIn, userName;
    try { isLoggedIn = localStorage.getItem('isLoggedIn'); userName = localStorage.getItem('userName'); } catch { /* Guest mode. */ }
    document.querySelectorAll('[data-game-navigation]').forEach(node => node.setAttribute('aria-label', t['nav-games']));
    if (userNameEl) {
        if (window.RE_PROFILE) {
            updateUserProfile();
        } else if (isLoggedIn === 'true' && userName) {
            userNameEl.textContent = userName;
        } else {
            userNameEl.textContent = t['nav-guest'];
        }
    }
}

function updateLangButtons(lang) {
    const btnEn = document.getElementById('btn-en');
    const btnRu = document.getElementById('btn-ru');
    
    if (btnEn && btnRu) {
        btnEn.classList.remove('active');
        btnRu.classList.remove('active');
        
        if (lang === 'en') {
            btnEn.classList.add('active');
        } else {
            btnRu.classList.add('active');
        }
    }
}

function getCurrentLang() {
    if (activeLanguage) return activeLanguage;
    try { return localStorage.getItem('lang') === 'ru' ? 'ru' : 'en'; } catch { return 'en'; }
}

function initializeLanguage() {
    const lang = getCurrentLang();
    applyLang(lang);
    updateLangButtons(lang);
}
if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', initializeLanguage, { once: true });
else initializeLanguage();

